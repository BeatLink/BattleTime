// Copies the files every watch needs that are not apps, such as the accelerometers' configuration, into the app:
// as base64 in src/bundles/system-files.ts for the window and the command line, and as plain files under
// core/system-files/ for the Rust core, each at its path on the watch.
//
//   node scripts/import-system-files.mjs path/to/store
//
// tools/build_store.py puts them in the store folder's system/ folder.

import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';

const source = process.argv[2];
if (!source) {
  console.error('Give the store folder tools/build_store.py filled.');
  process.exit(1);
}

const systemFolder = join(source, 'system');

function filesUnder(folder) {
  return readdirSync(folder)
    .sort()
    .flatMap((name) => {
      const path = join(folder, name);
      return statSync(path).isDirectory() ? filesUnder(path) : [path];
    });
}

const files = filesUnder(systemFolder).map((path) => ({
  watchPath: '/system/' + relative(systemFolder, path).split('\\').join('/'),
  bytes: readFileSync(path),
}));

rmSync('core/system-files', { recursive: true, force: true });
for (const { watchPath, bytes } of files) {
  const target = join('core/system-files', watchPath.slice('/system/'.length));
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, bytes);
}

const entries = files.map(({ watchPath, bytes }) => `  { path: '${watchPath}', base64: '${bytes.toString('base64')}' },`);
const output = `// Generated by \`npm run import-system-files <dir>\` from the store folder's system/ files. Do not edit by hand.
// The files every watch needs that are not apps, at their paths on the watch; the companion puts any a watch lacks.

export type BundledSystemFile = { path: string; base64: string };

export const SYSTEM_FILES: BundledSystemFile[] = [
${entries.join('\n')}
];
`;
writeFileSync('src/bundles/system-files.ts', output);
console.log(`Bundled ${files.length} system files into src/bundles/system-files.ts and core/system-files/.`);
