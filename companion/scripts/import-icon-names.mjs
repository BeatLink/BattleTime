// Copies the shared library's icon names, in their order, from a NeoTime checkout into src/bundles/icon-names.ts.
//
//   node scripts/import-icon-names.mjs path/to/NeoTime

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const neotime = process.argv[2];
if (!neotime) {
  console.error('Give the NeoTime checkout to copy the icon names from.');
  process.exit(1);
}

// The list is `pub const ICON_NAMES: [&str; N] = [ ... ];` in compiler/src/types.rs.
const types = readFileSync(join(neotime, 'compiler', 'src', 'types.rs'), 'utf8');
const match = /pub const ICON_NAMES: \[&str; (\d+)\] = \[([^\]]*)\];/.exec(types);
if (!match) {
  console.error('compiler/src/types.rs has no ICON_NAMES list.');
  process.exit(1);
}
const names = [...match[2].matchAll(/"([^"]+)"/g)].map((found) => found[1]);
if (names.length !== Number(match[1])) {
  console.error(`ICON_NAMES says ${match[1]} names but lists ${names.length}.`);
  process.exit(1);
}

const output = `// Generated by \`npm run import-icon-names <NeoTime dir>\` from ICON_NAMES in NeoTime's compiler/src/types.rs. Do not edit by hand.
// The shared library's icons, in the order the watch numbers them; icon-names.test.ts checks the order still matches.

export const LIBRARY_ICON_NAMES = [
${names.map((name) => `  '${name}',`).join('\n')}
] as const;

export type LibraryIconName = (typeof LIBRARY_ICON_NAMES)[number];
`;
writeFileSync('src/bundles/icon-names.ts', output);
console.log(`Copied ${names.length} icon names into src/bundles/icon-names.ts.`);
