#!/usr/bin/env node

// Turns packages built by wasp-os's tools/mkpkg.py into the module the app
// ships them in.
//
//   node scripts/import-packages.mjs path/to/wasp-os/build-packages
//
// Packages are embedded as base64 rather than bundled as assets, so they need
// no Metro configuration and behave the same on web as on a device. They are a
// few kilobytes each.

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const OUTPUT = 'src/packages/bundled.ts';

// Everything a package needs on the watch. Anything else in the directory is
// carried across as a resource.
const REQUIRED = ['app.mpy', 'meta.json'];

function readPackage(dir) {
  const name = basename(dir);
  const entries = readdirSync(dir).filter((entry) => statSync(join(dir, entry)).isFile());

  for (const required of REQUIRED) {
    if (!entries.includes(required)) {
      throw new Error(`${name}: missing ${required}`);
    }
  }

  const meta = JSON.parse(readFileSync(join(dir, 'meta.json'), 'utf8'));
  if (meta.name !== name) {
    throw new Error(`${name}: meta.json names it "${meta.name}"`);
  }

  const files = entries.sort().map((entry) => ({
    path: entry,
    base64: readFileSync(join(dir, entry)).toString('base64'),
  }));

  return { name, meta, files };
}

function render(packages) {
  const body = packages
    .map((pkg) => {
      const files = pkg.files
        .map((file) => `      { path: ${JSON.stringify(file.path)}, base64: ${JSON.stringify(file.base64)} },`)
        .join('\n');
      return [
        '  {',
        `    name: ${JSON.stringify(pkg.name)},`,
        `    meta: ${JSON.stringify(pkg.meta)},`,
        '    files: [',
        files,
        '    ],',
        '  },',
      ].join('\n');
    })
    .join('\n');

  return `// Generated by scripts/import-packages.mjs. Do not edit.
//
// Packages built from the wasp-os tree by tools/mkpkg.py, embedded so the app
// can install them with no network and no file system access.

import type { PackageMeta } from '@/protocol/packages';

export type BundledFile = { path: string; base64: string };

export type BundledPackage = {
  name: string;
  meta: PackageMeta;
  files: BundledFile[];
};

export const bundledPackages: BundledPackage[] = [
${body}
];
`;
}

function main() {
  const source = process.argv[2];
  if (!source) {
    console.error('usage: node scripts/import-packages.mjs <directory of built packages>');
    process.exit(2);
  }

  const dirs = readdirSync(source)
    .map((entry) => join(source, entry))
    .filter((path) => statSync(path).isDirectory())
    .sort();

  if (dirs.length === 0) {
    console.error(`no package directories under ${source}`);
    process.exit(1);
  }

  const packages = dirs.map(readPackage);
  writeFileSync(OUTPUT, render(packages));

  const bytes = packages.reduce(
    (total, pkg) => total + pkg.files.reduce((n, f) => n + Buffer.from(f.base64, 'base64').length, 0),
    0,
  );
  console.log(`${packages.length} packages, ${bytes} bytes -> ${OUTPUT}`);
  for (const pkg of packages) {
    console.log(`  ${pkg.name} ${pkg.meta.version} (${pkg.files.length} files)`);
  }
}

main();
