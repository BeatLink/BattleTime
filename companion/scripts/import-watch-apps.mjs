// Turns a folder of images compiled with BattleTime's battletime-compiler into the module the app bundles:
// the images the store starts with, and those setting up a new watch offers.
//
//   node scripts/import-watch-apps.mjs path/to/images
//
// tools/build_store.py fills such a folder with every app and face, and its store.json gives each one's
// description; without store.json the images are bundled without descriptions.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// What setting up a new watch offers: a face, the launcher and the apps most people keep.
const SETUP_IDS = new Set([
  'digital',
  'launcher',
  'calculator',
  'dice',
  'flashlight',
  'heart',
  'notes',
  'prompt',
  'puzzle15',
  'remote',
  'snake',
  'steps',
  'stopwatch',
  'timer',
]);

const source = process.argv[2];
if (!source) {
  console.error('Give the folder of .ntapp and .ntlib images.');
  process.exit(1);
}

const indexPath = join(source, 'store.json');
const index = existsSync(indexPath) ? JSON.parse(readFileSync(indexPath, 'utf8')) : { apps: [] };
const descriptions = new Map(index.apps.map((app) => [app.file, app.description]));

const files = readdirSync(source)
  .filter((name) => name.endsWith('.ntapp') || name.endsWith('.ntlib'))
  .sort();
const entries = files.map((file) => {
  const base64 = readFileSync(join(source, file)).toString('base64');
  const id = file.replace(/\.nt(app|lib)$/, '');
  const description = JSON.stringify(descriptions.get(file) ?? '').replaceAll("'", "\\'").slice(1, -1);
  const setup = file.endsWith('.ntlib') || SETUP_IDS.has(id);
  return `  { file: '${file}', setup: ${setup}, description: '${description}', base64: '${base64}' },`;
});

const output = `// Generated by \`npm run import-watch-apps <dir>\` from images battletime-compiler built. Do not edit by hand.
// Every app and face the store starts with, and the shared library; \`setup\` marks what a new watch is offered.

export type BundledImage = { file: string; base64: string; setup?: boolean; description?: string };

export const BUNDLED_IMAGES: BundledImage[] = [
${entries.join('\n')}
];
`;
writeFileSync('src/bundles/watch-apps.ts', output);
console.log(`Bundled ${files.length} images into src/bundles/watch-apps.ts.`);
