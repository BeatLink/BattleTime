// Turns a folder of images compiled with NeoTime's neotime-compiler into the module the app installs on a new watch.
//
//   node scripts/import-watch-apps.mjs path/to/images

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const source = process.argv[2];
if (!source) {
  console.error('Give the folder of .ntapp and .ntlib images.');
  process.exit(1);
}

const files = readdirSync(source)
  .filter((name) => name.endsWith('.ntapp') || name.endsWith('.ntlib'))
  .sort();
const entries = files.map((file) => {
  const base64 = readFileSync(join(source, file)).toString('base64');
  return `  { file: '${file}', base64: '${base64}' },`;
});

const output = `// Generated by \`npm run import-watch-apps <dir>\` from images neotime-compiler built. Do not edit by hand.
// The watch face, the launcher, the apps and the shared library a new watch is set up with.

export type BundledImage = { file: string; base64: string };

export const BUNDLED_IMAGES: BundledImage[] = [
${entries.join('\n')}
];
`;
writeFileSync('src/bundles/watch-apps.ts', output);
console.log(`Bundled ${files.length} images into src/bundles/watch-apps.ts.`);
